export function buildPageFromLayout(
  layout: PageLayoutPreset,
  pageWidth: number,
  pageHeight: number,
  options?: {
    backgroundColor?: string;
    backgroundPattern?: BackgroundPattern;
    fontFamily?: string;
    strokeColor?: string;
    strokeWidth?: number;
    existingImages?: (string | null)[];
    headerBanner?: ComicTemplate['headerBanner'];
  }
): ComicPage {
  const margin = 30;
  const gutter = 12;
  const topOffset = options?.headerBanner ? 110 : margin;
  const cw = pageWidth - margin * 2;
  const ch = pageHeight - topOffset - margin;

  const elements: ComicPage['elements'] = [];
  if (options?.headerBanner) {
    elements.push(
      createLettering({
        text: options.headerBanner.text,
        fontFamily: options.fontFamily || 'Bangers',
        x: margin,
        y: 22,
        width: cw,
        height: 74,
        rotation: 0,
        fontSize: 44,
        fillTopColor: options.headerBanner.color,
        fillBottomColor: options.headerBanner.bg,
        strokeColor: options.headerBanner.stroke || '#000000',
        strokeWidth: 2,
        warp: 'none',
        zIndex: 35,
      })
    );
  }

  layout.slots.forEach((slot, idx) => {
    const px = Math.round(margin + slot.nx * cw);
    const py = Math.round(topOffset + slot.ny * ch);
    const pw = Math.round(slot.nw * cw);
    const ph = Math.round(slot.nh * ch);
    const existingImg = options?.existingImages?.[idx] ?? null;

    elements.push(
      createPanel({
        x: px,
        y: py,
        width: pw,
        height: ph,
        shape: slot.shape ?? 'rect',
        cornerRadius: slot.cornerRadius ?? 0,
        strokeColor: options?.strokeColor ?? '#000000',
        strokeWidth: options?.strokeWidth ?? 2,
        imageUrl: existingImg,
        zIndex: idx + 1,
      })
    );
  });

  return {
    id: nextId('page'),
    backgroundColor: options?.backgroundColor ?? '#ffffff',
    backgroundPattern: options?.backgroundPattern ?? 'none',
    margin,
    gutter,
    elements,
  };
}

