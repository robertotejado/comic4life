let uidCounter = 100;
export function nextId(prefix = 'el'): string {
  uidCounter += 1;
  return `${prefix}-${Date.now().toString(36)}-${uidCounter}`;
}

export function createPanel(
  partial: Partial<PanelElement> & { x: number; y: number; width: number; height: number }
): PanelElement {
  return {
    id: partial.id || nextId('panel'),
    kind: 'panel',
    x: partial.x,
    y: partial.y,
    width: partial.width,
    height: partial.height,
    rotation: partial.rotation ?? 0,
    opacity: partial.opacity ?? 100,
    zIndex: partial.zIndex ?? 1,
    shape: partial.shape ?? 'rect',
    cornerRadius: partial.cornerRadius ?? 0,
    strokeColor: partial.strokeColor ?? '#ffffff',
    strokeWidth: partial.strokeWidth ?? 1,
    strokeEnabled: partial.strokeEnabled ?? true,
    fillColor: partial.fillColor ?? '#ffffff',
    fillEnabled: partial.fillEnabled ?? true,
    shadow: partial.shadow ?? false,
    shadowColor: partial.shadowColor ?? 'rgba(0,0,0,0.45)',
    padding: partial.padding ?? 0,
    imageUrl: partial.imageUrl ?? null,
    imageScale: partial.imageScale ?? 1,
    imageOffsetX: partial.imageOffsetX ?? 0,
    imageOffsetY: partial.imageOffsetY ?? 0,
    imageFilter: partial.imageFilter ?? 'none',
    brightness: partial.brightness ?? 100,
    contrast: partial.contrast ?? 100,
    saturation: partial.saturation ?? 100,
    instantAlpha: partial.instantAlpha ?? {
      enabled: false,
      color: '#ffffff',
      tolerance: 25,
    },
  };
}

export function createBalloon(
  partial: Partial<BalloonElement> & { x: number; y: number; width: number; height: number }
): BalloonElement {
  const bType = partial.balloonType ?? 'speech';
  const cx = partial.x + partial.width / 2;
  const cy = partial.y + partial.height;
  return {
    id: partial.id || nextId('balloon'),
    kind: 'balloon',
    balloonType: bType,
    x: partial.x,
    y: partial.y,
    width: partial.width,
    height: partial.height,
    rotation: partial.rotation ?? 0,
    opacity: partial.opacity ?? 100,
    zIndex: partial.zIndex ?? 20,
    text:
      partial.text ??
      (bType === 'caption'
        ? 'Caption text...'
        : bType === 'text'
          ? 'Double-click to type...'
          : bType === 'burst'
            ? 'HOLD ON!'
            : 'Speak here!'),
    fontFamily: partial.fontFamily ?? 'Comic Neue',
    fontSize: partial.fontSize ?? (bType === 'text' ? 20 : 16),
    fontWeight: partial.fontWeight ?? 'bold',
    italic: partial.italic ?? false,
    underline: partial.underline ?? false,
    lineHeight: partial.lineHeight ?? 1.2,
    letterSpacing: partial.letterSpacing ?? 0,
    textAlign: partial.textAlign ?? 'center',
    textColor: partial.textColor ?? '#111827',
    fillColor:
      partial.fillColor ?? (bType === 'caption' ? '#fef9c3' : '#ffffff'),
    fillEnabled: partial.fillEnabled ?? (bType !== 'text'),
    strokeColor: partial.strokeColor ?? '#000000',
    strokeWidth: partial.strokeWidth ?? 2,
    strokeEnabled: partial.strokeEnabled ?? (bType !== 'text'),
    shadow: partial.shadow ?? (bType !== 'text'),
    cornerRadius: partial.cornerRadius ?? (bType === 'caption' ? 2 : 12),
    padding: partial.padding ?? 8,
    tail: partial.tail ?? {
      enabled: bType !== 'caption' && bType !== 'text',
      tipX: cx - 18,
      tipY: cy + 34,
      style: bType === 'thought' ? 'bubbles' : 'curved',
      width: 18,
    },
  };
}

